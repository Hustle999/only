/**
 * Захианы текстийг боловсруулах туслах функц:
 * Хэрэв үндсэн placeholder хэвээр байвал төвийг сахисан урьдчилсан текстийг буцаана.
 */
export function getResolvedLetterText(text: string): string {
  const trimmed = text.trim();
  if (
    !trimmed ||
    trimmed === "[PASTE_YOUR_LETTER_HERE]" ||
    trimmed === "PASTE_YOUR_LETTER_HERE"
  ) {
    return "Чамд хэлэх гэсэн хэдэн үгээ энд үлдээлээ.";
  }
  return text;
}

export function isPlaceholderName(name: string): boolean {
  const trimmed = name.trim();
  return (
    !trimmed ||
    trimmed === "[HER_NAME]" ||
    trimmed === "[YOUR_NAME]" ||
    trimmed === "HER_NAME" ||
    trimmed === "YOUR_NAME"
  );
}
